/* ============================================================================
   咒术闲录 · 自定义特效间隔（模板）
   ----------------------------------------------------------------------------
   这个夹子只干一件事：多图连播时，每张图停留多久。

   用法：把本文件复制一份、改个名（别用 _ 开头），把下面被注释掉的那几行放出来，
   改成你自己的；不用的行删掉就行。一行 = 一条规则。

   match 能写什么，和「自定义特效」完全一样：
     skill  某一门术式 id           例：k_punch
     innate 某一系生得术式 id       例：t_jukai
     dom    某个领域的 domKind      例：infoOverload
     kind   动作类别                例：bf / phy / ink / summon / domain
     id     术式 id 或生得术式 id 都认
   不写 match 的那一条，是「谁都命中不到时」用的兜底默认。
   ============================================================================ */
(function () {
  var C = window.JH_CUSTOM;
  if (!C) return;
  C['特效间隔'] = C['特效间隔'] || [];

  /* ① 兜底默认：所有多图连播都是每张 300ms（不写这条就用本体的 450ms）
  C['特效间隔'].push({ default: 300 });
  */

  /* ② 某一门术式：每张图停留 180ms
  C['特效间隔'].push({ match: { skill: 'k_punch' }, ms: 180 });
  */

  /* ③ 逐张指定：第 1 张 120ms、第 2 张 200ms、第 3 张起 340ms
  C['特效间隔'].push({ match: { innate: 't_jukai' }, ms: 340, frames: [120, 200] });
  */

  /* ④ 只调第一张 / 最后一张（领域展开那种）
  C['特效间隔'].push({ match: { kind: 'domain' }, first: 300, last: 700 });
  */
})();
